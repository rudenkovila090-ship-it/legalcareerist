/** Журнал доставок: по строке на человека { c, id, r, at }; r — ok, blocked или failed. */
export function logDelivery(campaignId, tgId, result) {
  fs.mkdirSync(DATA_DIR, { recursive: true })
  fs.appendFileSync(LOG_FILE, `${JSON.stringify({ c: campaignId, id: String(tgId), r: result, at: Date.now() })}\n`)
}

/** Кому рассылка уже обработана (доставлено или бот заблокирован): таким повторно не пишем. Неудачные (failed) пробуем ещё раз. */
export function deliveredSet(campaignId) {
  const done = new Set()
  try {
    for (const line of fs.readFileSync(LOG_FILE, 'utf8').split('\n')) {
      if (!line) continue
      const rec = JSON.parse(line)
      if (rec.c === campaignId && (rec.r === 'ok' || rec.r === 'blocked')) done.add(rec.id)
    }
  } catch {
    // журнала ещё нет
  }
  return done
}

export function deliveryCounts(campaignId) {
  const last = new Map()
  try {
    for (const line of fs.readFileSync(LOG_FILE, 'utf8').split('\n')) {
      if (!line) continue
      const rec = JSON.parse(line)
      if (rec.c === campaignId) last.set(rec.id, rec.r)
    }
  } catch {
    // журнала ещё нет
  }
  const counts = { ok: 0, blocked: 0, failed: 0 }
  for (const r of last.values()) counts[r] = (counts[r] ?? 0) + 1
  return counts
}

