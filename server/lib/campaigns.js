/** Что с рассылкой сейчас: sent / running / paused / preview (тест отправлен, ждём) / scheduled. */
export function statusOf(c, state, now) {
  if (state.finishedAt) return 'sent'
  if (state.paused) return 'paused'
  if (state.startedAt) return 'running'
  if (state.previewAt) return 'preview'
  return now >= c.sendAt - PREVIEW_LEAD_MS ? 'preview-due' : 'scheduled'
}

