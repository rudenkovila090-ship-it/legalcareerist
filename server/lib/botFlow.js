// Воронка бота (перенос из BotHelp), блок за блоком. Тексты — из сценария BotHelp.
// Блок 1: старт → метка «пользователь» → приветствие с согласием на обработку ПД.

// Ключевые слова запуска из блока «Старт» (срабатывают, если слово содержится в сообщении).
export const START_KEYWORDS = ['вступить в сообщество', 'привет', 'запустить', 'старт', 'поехали', 'хай', 'начать', 'здравствуйте', 'карьера']

export function isStartKeyword(text) {
  const t = String(text ?? '').toLowerCase()
  return START_KEYWORDS.some((k) => t.includes(k))
}

/** Сообщение 2 из BotHelp: приветствие и просьба подтвердить согласие. */
export function welcomeScreen(firstName, siteUrl) {
  return {
    text: [
      `Привет, ${firstName || 'друг'}! 👋`,
      'Я — чат-бот «Карьерный юрист». Помогаю тебе:',
      '- вступить в сообщество',
      '- зарегистрироваться на мероприятия',
      '- записаться на консультации',
      '- приобрести полезные материалы',
      '',
      'Перед началом работы, пожалуйста, ознакомься с политикой обработки персональных данных и подтверди согласие. Это нужно, чтобы я мог комфортно и безопасно с тобой взаимодействовать.',
      '',
      'Нажимая «Ознакомлен и согласен», ты подтверждаешь, что прочитал и принимаешь Политику обработки персональных данных и Согласие на обработку персональных данных.',
    ].join('\n'),
    keyboard: [
      [{ text: 'Политика обработки персональных данных', url: `${siteUrl}/legal/privacy` }],
      [{ text: 'Согласие на обработку персональных данных', url: `${siteUrl}/legal/consent` }],
      [{ text: '✅ Ознакомлен и согласен', callback_data: 'u:consent' }],
    ],
  }
}

