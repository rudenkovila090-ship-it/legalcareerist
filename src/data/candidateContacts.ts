// База кандидатов «Найти сотрудника» (см. KadryHome.tsx) — реальные анкеты,
// заполняются по одной вручную, а не генерируются из шаблона. Вынесено в
// отдельный модуль, чтобы теми же карточками можно было пользоваться и в
// кабинете работодателя (EmployerAccount.tsx → вкладка «Кандидаты»), не
// дублируя данные.
export interface CandidateContact {
  id: number
  position: string
  sphere: string
  exp: string
  salaryFrom: string
  city: string
  schedule: string
  employment: string
  format: string
  workplace: string
  duties: string[]
  highlights: string[]
  publications?: string[]
  school: string
  course: string
  skills: string[]
  /** Стоимость контакта у части кандидатов фиксирована отдельно (не по
   *  общей прогрессивной шкале от опыта, см. contactPrice ниже). */
  contactPriceOverride?: number
}

// Прогрессивная шкала: чем опытнее кандидат, тем дороже открыть его контакт.
export function experienceYears(exp: string) {
  if (exp === 'без опыта') return 0
  const n = Number(exp.match(/\d+/)?.[0])
  return Number.isFinite(n) ? n : 0
}
export function contactPrice(exp: string) {
  return 1000 + experienceYears(exp) * 500
}
export function candidateContactPrice(c: { exp: string; contactPriceOverride?: number }) {
  return c.contactPriceOverride ?? contactPrice(c.exp)
}

