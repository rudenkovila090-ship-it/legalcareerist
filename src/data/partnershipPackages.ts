/** Подпись формата для заявки: «Информационный партнёр — 10 000 ₽». */
export function partnershipFormatLabel(id: string): string {
  const p = partnershipPackages.find((x) => x.id === id)
  return p ? `${p.title} — ${p.price.toLocaleString('ru-RU')} ₽` : 'Пока не определились, обсудим'
}
