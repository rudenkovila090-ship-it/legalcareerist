// Авторское оформление и тексты отдельных мероприятий. Лежит отдельно от events.ts:
// тот файл читает скрипт выгрузки каталога для бота (scripts/export-vacancy-catalog.mjs),
// а он не умеет подключать картинки. Если у мероприятия есть запись здесь (по slug),
// его страница получает тёмную тему и блоки «О вечере», «Досье», «Для кого», «Сюжет», «Спикеры».

export type CharacterIcon = 'hat' | 'glass' | 'magnifier' | 'pearl' | 'scales' | 'key'

/**
 * Приглашённый гость, исполняющий роль. Пока поля нет у персонажа — его папка в блоке «Спикеры» остаётся
 * закрытой («имя позже»); когда заполнено — папка подписана именем. Тему, вопросы и пункты блокнота можно
 * добавить позже: пока их нет, в деле они остаются закрытыми.
 */
export interface EventSpeaker {
  name: string
  /** Должность или регалия: «Основатель Карьерного юриста». */
  position?: string
  /** Фото гостя; пока его нет — в деле стоит силуэт. */
  photo?: string
  /** Название выступления. */
  topic?: string
  /** Одна фраза-подзаголовок под названием. */
  topicLead?: string
  /** «Подозреваемый» — что именно разбирается на выступлении; красный штамп в «показаниях». */
  suspect?: string
  /** Описание выступления: о чём, зачем, что получит слушатель. */
  description?: string
  /** «Смысл» — как выступление вписано в сюжет вечера. */
  meaning?: string
  /** Роль гостя на вечере одной фразой — строка в листе «Роль в деле». */
  roleNote?: string
  /** «О чем расскажет» сплошным текстом (если нет списка themes). */
  about?: string
  /** Реплика гостя в образе — цитата в «показаниях» (если нет названия выступления). */
  testimony?: string
  /** Вопросы выступления — «показания» в деле. */
  questions?: string[]
  /** О чём расскажет: пункты блокнота. */
  themes?: string[]
  /** Уровень риска темы (1–5) — шкала в углу дела. */
  risk?: 1 | 2 | 3 | 4 | 5
  /** 'route' — на схеме показан след публикации (для темы про цифровой след); по умолчанию — «место происшествия». */
  map?: 'route'
}

export interface EventCharacter {
  name: string
  /** Короткая подпись под именем: «глава мафии». */
  epithet: string
  /** Ключевые слова роли: «Власть · Деньги · Договорённости». */
  keywords: string
  text: string
  motive: string
  symbol: string
  icon: CharacterIcon
  /** Номер дела на папке и обложке: четыре цифры, у каждой роли свой. */
  caseNo?: string
  /** Гость в этой роли — заполняем, когда имя объявлено. */
  speaker?: EventSpeaker
}

export interface EventAct {
  /** Частота «волны», на которой этот акт идет в эфир (блок «Сюжет вечера» — радиоприемник). */
  freq: number
  title: string
  paragraphs: string[]
  /** Закрытая плашка в конце акта (спойлер, который не показываем до вечера). */
  sealed?: string
}

/** Дополнительная радиоволна: ночной эфир города между актами. */
export interface RadioStation {
  id: string
  /** Короткая подпись на клавише приемника. */
  short: string
  name: string
  description: string
  freq: number
  /** Волна без передачи — одни помехи. */
  silent?: boolean
}

/** Кому подойдёт вечер: «фото» на стене улик, подпись появляется при наведении. */
export interface EventAudience {
  who: string
  photo: string
}

/** Строка программы: время и название; role — имя роли (EventCharacter.name), если это выступление спикера. */
export interface ProgramSlot {
  time: string
  title: string
  role?: string
  /** Короткая подпись под строкой программы. */
  note?: string
}

/** Акт программы: заголовок и вложенные слоты; время акта считается по первому и последнему слоту. */
export interface ProgramAct {
  title: string
  slots: ProgramSlot[]
}

export type ProgramEntry = ProgramSlot | ProgramAct

/** Страница газеты «Новости бара». Пока страница одна — главная; новые добавляются в paper.pages. */
export interface NewsPage {
  /** Название страницы для счётчика и скринридера: «Главная». */
  section: string
  kicker?: string
  headline: string
  subhead?: string
  lead?: string
  paragraphs?: string[]
  /** Врезка-цитата; если text не задан, берется вопрос вечера. */
  quote?: { label: string; text?: string }
  /** Фото в чёрно-белом растре (сейчас — сцена закрытого бара) с подписью. */
  photo?: { caption: string }
  /** Блок «Анонс» (дата, время, место, вход) и купон на билет — собирается из данных мероприятия. */
  announce?: boolean
  /** Вместо статьи — игра «найди слова»: сетка букв и список слов. */
  puzzle?: WordSearch
}

/**
 * Филворд на странице газеты. Слова читаются только вперёд: слева направо, сверху вниз и по диагонали вниз вправо.
 * grid — строки одинаковой длины; каждое слово из words встречается в сетке ровно один раз.
 */
export interface WordSearch {
  grid: string[]
  words: string[]
  /** Как играть (короткая подсказка под сеткой). */
  hint?: string
  /** Девиз внизу страницы. */
  motto?: string
}

export interface EventPaper {
  name: string
  motto: string
  pages: NewsPage[]
}

/** Страница «Досье вечера»: либо текст, либо список пунктов «заголовок — пояснение». */
export interface FactPage {
  label: string
  text?: string
  items?: { title: string; text: string }[]
}

/** Партнёр вечера — «член семьи». */
export interface EventPartner {
  /** Подпись под картинкой. */
  name: string
  description?: string
  /** Круглая картинка (логотип или фото); контур — часть самого изображения. */
  logo?: string
  /** Кликабельная ссылка под подписью: label — как показать, href — куда ведёт. */
  link?: { label: string; href: string }
}

/** Группа партнёров: «Информационные партнеры», «Генеральный партнер» и т. п. */
export interface FamilyGroup {
  title: string
  members: EventPartner[]
}

/** Блок «Члены семьи»: рассказ о партнёрах по группам. Пока партнёров нет, показывается только вводная. */
export interface EventFamily {
  groups: FamilyGroup[]
}

export interface EventStory {
  /** Адрес площадки без города (город берется из мероприятия): показывается в верхней строке страницы. */
  venue?: string
  /** Вопрос вечера. */
  tagline: string
  /** Картинки: сцена для шапки и портрет для блока «О вечере». */
  heroImage: string
  portraitImage: string
  /** Широкая обложка карточки в афише (растягивается на всю ширину строки). */
  cardImage: string
  introLead: string
  intro: string[]
  /** Вопрос из текста перед ним — вводная фраза. */
  questionLead: string
  question: string
  /** Страницы «папки с делом» («Досье вечера»): цель, формат, жанр, для кого. */
  facts: FactPage[]
  /** Для кого — стена с фото и красными нитками. */
  audience: EventAudience[]
  principle: string
  acts: EventAct[]
  /** Дополнительные радиоволны блока «Сюжет вечера» (акты занимают три своих волны). */
  radio: RadioStation[]
  /** Газета «Новости бара» — листается по клику. */
  paper?: EventPaper
  /** «Члены семьи» — партнёры вечера. */
  family: EventFamily
  /** Программа вечера. */
  program: ProgramEntry[]
  /** Роль (EventCharacter.name), которую исполняет ведущая вечера, — показывается в программе. */
  hostRole?: string
  /** Вводная к блоку «Спикеры» — папки с делами гостей. */
  speakersIntro: string
  characters: EventCharacter[]
}

