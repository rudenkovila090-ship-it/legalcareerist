// Авторское оформление и тексты отдельных мероприятий. Лежит отдельно от events.ts:
// тот файл читает скрипт выгрузки каталога для бота (scripts/export-vacancy-catalog.mjs),
// а он не умеет подключать картинки. Если у мероприятия есть запись здесь (по slug),
// его страница получает тёмную тему и блоки «О вечере», «Досье», «Для кого», «Сюжет», «Спикеры».

export type CharacterIcon = 'hat' | 'glass' | 'magnifier' | 'pearl' | 'scales' | 'key'

/**
 * Приглашённый гость, исполняющий роль. Пока поля нет у персонажа — его папка в блоке «Спикеры» остаётся
 * закрытой («имя позже»); когда заполнено — папка подписана именем. Тему, вопросы и пункты блокнота можно
 * добавить позже: пока их нет, в деле они остаются закрытыми.
 */
export interface EventSpeaker {
  name: string
  /** Должность или регалия: «Основатель Карьерного юриста». */
  position?: string
  /** Фото гостя; пока его нет — в деле стоит силуэт. */
  photo?: string
  /** Название выступления. */
  topic?: string
  /** Одна фраза-подзаголовок под названием. */
  topicLead?: string
  /** «Подозреваемый» — что именно разбирается на выступлении; красный штамп в «показаниях». */
  suspect?: string
  /** Описание выступления: о чём, зачем, что получит слушатель. */
  description?: string
  /** «Смысл» — как выступление вписано в сюжет вечера. */
  meaning?: string
  /** Роль гостя на вечере одной фразой — строка в листе «Роль в деле». */
  roleNote?: string
  /** «О чем расскажет» сплошным текстом (если нет списка themes). */
  about?: string
  /** Реплика гостя в образе — цитата в «показаниях» (если нет названия выступления). */
  testimony?: string
  /** Вопросы выступления — «показания» в деле. */
  questions?: string[]
  /** О чём расскажет: пункты блокнота. */
  themes?: string[]
  /** Уровень риска темы (1–5) — шкала в углу дела. */
  risk?: 1 | 2 | 3 | 4 | 5
  /** 'route' — на схеме показан след публикации (для темы про цифровой след); по умолчанию — «место происшествия». */
  map?: 'route'
}

export interface EventCharacter {
  name: string
  /** Короткая подпись под именем: «глава мафии». */
  epithet: string
  /** Ключевые слова роли: «Власть · Деньги · Договорённости». */
  keywords: string
  text: string
  motive: string
  symbol: string
  icon: CharacterIcon
  /** Гость в этой роли — заполняем, когда имя объявлено. */
  speaker?: EventSpeaker
}

export interface EventAct {
  title: string
  paragraphs: string[]
  /** Закрытая плашка в конце акта (спойлер, который не показываем до вечера). */
  sealed?: string
}

/** Кому подойдёт вечер: «фото» на стене улик, подпись появляется при наведении. */
export interface EventAudience {
  who: string
  photo: string
}

/** Строка программы: время и название; role — имя роли (EventCharacter.name), если это выступление спикера. */
export interface ProgramSlot {
  time: string
  title: string
  role?: string
  /** Короткая подпись под строкой программы. */
  note?: string
}

/** Акт программы: заголовок и вложенные слоты; время акта считается по первому и последнему слоту. */
export interface ProgramAct {
  title: string
  slots: ProgramSlot[]
}

export type ProgramEntry = ProgramSlot | ProgramAct

/** Партнёр вечера — «член семьи». */
export interface EventPartner {
  name: string
  description?: string
  logo?: string
  url?: string
}

/** Блок «Члены семьи»: рассказ о партнёрах. Пока партнёры не объявлены, показывается только вводная. */
export interface EventFamily {
  intro: string
  members: EventPartner[]
}

export interface EventStory {
  /** Вопрос вечера. */
  tagline: string
  /** Картинки: сцена для шапки и портрет для блока «О вечере». */
  heroImage: string
  portraitImage: string
  /** Широкая обложка карточки в афише (растягивается на всю ширину строки). */
  cardImage: string
  introLead: string
  intro: string[]
  /** Вопрос из текста перед ним — вводная фраза. */
  questionLead: string
  question: string
  /** Страницы «папки с делом» («Досье вечера»): цель, формат, жанр, для кого. */
  facts: { label: string; text: string }[]
  /** Для кого — стена с фото и красными нитками. */
  audience: EventAudience[]
  principle: string
  /** Подсказка в форме билета над полем промокода. */
  promoNote?: string
  acts: EventAct[]
  /** «Члены семьи» — партнёры вечера. */
  family: EventFamily
  /** Программа вечера. */
  program: ProgramEntry[]
  /** Роль (EventCharacter.name), которую исполняет ведущая вечера, — показывается в программе. */
  hostRole?: string
  /** Вводная к блоку «Спикеры» — папки с делами гостей. */
  speakersIntro: string
  characters: EventCharacter[]
}

