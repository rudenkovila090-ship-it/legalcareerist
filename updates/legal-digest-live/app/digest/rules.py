# --- Даты ----------------------------------------------------------------------------------------
MONTHS = {
    "января": 1, "февраля": 2, "марта": 3, "апреля": 4, "мая": 5, "июня": 6,
    "июля": 7, "августа": 8, "сентября": 9, "октября": 10, "ноября": 11, "декабря": 12,
}
_MONTHS_RE = "|".join(MONTHS)
# «28 октября», «10–12 ноября», «с 10 по 12 ноября», «28 октября 2026»
_TEXT_DATE = re.compile(
    rf"(?<!\d)(\d{{1,2}})(?:\s*(?:[-–—]|по)\s*\d{{1,2}})?\s+({_MONTHS_RE})(?:\s+(20\d{{2}}))?(?!\w)",
    re.IGNORECASE,
)
# «05.11», «28.10.2026», «28.10.26». Месяц только двумя цифрами, чтобы «3.5 года опыта» не стало датой.
_NUM_DATE = re.compile(r"(?<![\d.,/])(\d{1,2})\.(0[1-9]|1[0-2])(?:\.(\d{4}|\d{2}))?(?!\d)(?!\.\d)")
_RELATIVE = re.compile(r"\b(сегодня|завтра|послезавтра)\b", re.IGNORECASE)
_TIME = re.compile(r"(?<![\d:.])([01]?\d|2[0-3]):([0-5]\d)(?![\d:])")
# «регистрация до 27 октября», «подписка до 1 ноября», «дедлайн: 27.10» — это срок, а не дата мероприятия.
_DEADLINE_CUE = re.compile(
    r"(дедлайн|(регистрац|заявк|запис|подач|прием|подписк|оплат|скидк|акци|успе|действует)\w*[^\n]{0,30}\bдо)\W*$"
)


def normalize(text: str) -> str:
    return text.lower().replace("ё", "е")


@dataclass(frozen=True)
class Match:
    kind: str  # "event" | "vacancy" | "news" | "law"
    title: str
    event_date: date | None  # у законодательства: дата вступления в силу
    event_time: time | None
    deadline: date | None
    # Вакансии: данные для работы с работодателем.
    company: str | None = None
    salary: str | None = None
    work_format: str | None = None  # у вакансии: офис / удалённо / гибрид; у мероприятия: онлайн / офлайн / гибрид
    contacts: tuple[str, ...] = ()
    via_agency: bool = False
    # Мероприятия: карточка.
    event_end: time | None = None
    city: str | None = None  # и у мероприятий, и у вакансий
    price: str | None = None
    audience: tuple[str, ...] = ()
    topic: str | None = None  # «О чём»: выдержка из поста; у новостей краткое содержание
    reg_url: str | None = None
    # Новости о людях и законодательство.
    subtype: str | None = None
    people: tuple[str, ...] = ()
    role: str | None = None  # должность человека
    origin: str | None = None  # откуда перешёл
    place: str | None = None  # у наград: какая награда; у законодательства: орган или суд
    doc_ref: str | None = None  # номер закона или судебного дела
    # Любой тип: ссылки из самого поста, которые ведут куда-то (регистрация, hh.ru, документ, форма, бот).
    links: tuple[str, ...] = ()


@dataclass(frozen=True)
class _Hit:
    day: date
    start: int
    deadline: bool


def _safe_date(year: int, month: int, day: int) -> date | None:
    try:
        return date(year, month, day)
    except ValueError:
        return None


def _with_year(day: int, month: int, year: int | None, ref: date) -> date | None:
    if year is not None:
        return _safe_date(year, month, day)
    result = _safe_date(ref.year, month, day)
    # Пост от 20 декабря про «15 января» — это январь следующего года.
    if result and result < ref - timedelta(days=60):
        result = _safe_date(ref.year + 1, month, day)
    return result


def _is_deadline(text: str, start: int) -> bool:
    head = normalize(text[max(0, start - 50):start]).rsplit("\n", 1)[-1]
    return bool(_DEADLINE_CUE.search(head))


def find_dates(text: str, ref: date) -> list[_Hit]:
    hits: list[_Hit] = []
    for m in _TEXT_DATE.finditer(text):
        year = int(m[3]) if m[3] else None
        day = _with_year(int(m[1]), MONTHS[m[2].lower()], year, ref)
        if day:
            hits.append(_Hit(day, m.start(), _is_deadline(text, m.start())))
    for m in _NUM_DATE.finditer(text):
        year = int(m[3]) if m[3] else None
        if year is not None:
            year = year + 2000 if year < 100 else year
            if not 2000 <= year <= 2100:
                continue
        day = _with_year(int(m[1]), int(m[2]), year, ref)
        if day:
            hits.append(_Hit(day, m.start(), _is_deadline(text, m.start())))
    if not hits:
        offsets = {"сегодня": 0, "завтра": 1, "послезавтра": 2}
        for m in _RELATIVE.finditer(text):
            hits.append(_Hit(ref + timedelta(days=offsets[m[1].lower()]), m.start(), False))
    return hits


def find_time(text: str, after: int) -> time | None:
    m = _TIME.search(text, after) or _TIME.search(text)
    return time(int(m[1]), int(m[2])) if m else None


def find_time_range(text: str, after: int) -> tuple[time | None, time | None]:
    """Время начала и, если указано, окончания: «15:00–16:30»."""
    m = _TIME_RANGE.search(text, after) or _TIME_RANGE.search(text)
    if m:
        return time(int(m[1]), int(m[2])), time(int(m[3]), int(m[4]))
    return find_time(text, after), None


def find_price(text: str) -> str | None:
    """«Бесплатно» (с пометкой «по регистрации»), сумма из текста или «Платно»; иначе None."""
    low = normalize(text)
    if _FREE.search(low):
        return "Бесплатно, по регистрации" if "регистрац" in low else "Бесплатно"
    label = _PAID_LABEL.search(low)
    if label:
        money = _MONEY.search(text, label.end(), label.end() + 80)
        return " ".join(money[0].split()).rstrip(" ,;") if money else "Платно"
    return None


def find_event_format(text: str) -> str | None:
    """онлайн, офлайн или гибрид; None, если из текста не понять."""
    low = normalize(text)
    online, offline = bool(_ONLINE.search(low)), bool(_OFFLINE.search(low))
    if _HYBRID.search(low) or (online and offline):
        return "гибрид"
    if online:
        return "онлайн"
    return "офлайн" if offline else None


def find_city(text: str) -> str | None:
    """Город из словаря: тот, что упомянут раньше всех."""
    low = normalize(text)
    best: tuple[int, str] | None = None
    for name, pattern in _CITIES:
        m = pattern.search(low)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), name)
    return best[1] if best else None


def find_audience(low: str) -> tuple[str, ...]:
    """Для кого полезно: «инхаусам», «адвокатам», «руководителям»… `low` — нормализованный текст."""
    return tuple(label for label, pattern in _AUDIENCE if pattern.search(low))[:3]


def first_link(text: str, urls: tuple[str, ...] = ()) -> str | None:
    """Первая внешняя ссылка поста (регистрация, подробности), в том числе спрятанная за словами."""
    for url in [*urls, *_URL.findall(text)]:
        url = url.rstrip(".,;:!?")
        if "t.me/" not in url:
            return url
    return None


def link_key(url: str) -> str:
    """Ссылка для сравнения: без схемы, «www», завершающего слеша, якоря и меток utm_*. Так одна и та же
    страница, записанная по-разному, считается одной."""
    parts = urlsplit(url.strip())
    query = urlencode([(k, v) for k, v in parse_qsl(parts.query) if not k.lower().startswith(("utm_", "fbclid", "yclid"))])
    host = parts.netloc.lower().removeprefix("www.")
    return f"{host}{parts.path.rstrip('/')}" + (f"?{query}" if query else "")


def _is_own_channel_root(url: str, username: str | None, channel_id: int | None) -> bool:
    """«Подписывайтесь: t.me/канал» — ссылка на сам канал, а не на что-то из поста."""
    parts = urlsplit(url)
    if parts.netloc.lower().removeprefix("www.") not in ("t.me", "telegram.me"):
        return False
    path = [part for part in parts.path.split("/") if part]
    if username and len(path) == 1 and path[0].lower() == username.lower():
        return True
    return channel_id is not None and path == ["c", str(channel_id)]


def find_links(
    text: str, urls: tuple[str, ...] = (), channel_username: str | None = None, channel_id: int | None = None,
    limit: int = 4,
) -> tuple[str, ...]:
    """Ссылки из самого поста, которые ведут куда-то: на регистрацию, документ, форму, hh.ru, бота, другой пост.
    Берутся и открытые ссылки в тексте, и спрятанные за словами или кнопками (`urls`). Не берутся повторы,
    ссылки не на сайты (tg://, mailto:) и ссылка на сам канал-источник."""
    found: list[str] = []
    seen: set[str] = set()
    for url in [*urls, *_URL.findall(text)]:
        url = url.strip().rstrip(".,;:!?»\"”")
        if not url.lower().startswith(("http://", "https://")) or _is_own_channel_root(url, channel_username, channel_id):
            continue
        key = link_key(url)
        if key not in seen:
            seen.add(key)
            found.append(url)
    return tuple(found[:limit])


def find_people(text: str) -> tuple[str, ...]:
    """Люди по имени и фамилии: известное имя рядом со словом, похожим на фамилию или отчество. Имена
    в косвенных падежах («назначение Ольги Романовой») приводятся к именительному: «Ольга Романова»."""
    people: list[str] = []
    for m in _CAP_PAIR.finditer(text):
        a, b = m.group(1), m.group(2)
        found = _person(a, b)
        name = f"{found[0]} {found[1]}" if found else None
        if not found and (found := _person(b, a)):  # фамилия впереди: «Голованёв Михаил»
            name = f"{found[1]} {found[0]}"
        if name and name not in people:
            people.append(name)
    return tuple(people[:4])


def _clean_org(raw: str | None) -> str | None:
    """Название организации без кавычек и знаков препинания; людей, местоимения и общие слова отбрасываем."""
    if not raw:
        return None
    name = " ".join(raw.strip().strip("«»\"“” ").split()).strip(" .,:;")
    low = normalize(name)
    if len(name) < 2 or low in _NOT_ORG:
        return None
    if find_people(name) and not _FIRM_MARK.search(low):
        return None
    return name[:60]


def _first_org(patterns, text: str) -> str | None:
    for pattern in patterns:
        for m in pattern.finditer(text):
            org = _clean_org(m["org"])
            if org:
                return org
    return None


def find_move(text: str) -> tuple[str | None, str | None]:
    """Откуда и куда перешёл человек: («Dentons», «Пепеляев Групп»). Чего в тексте нет, то None."""
    company = _first_org((_TO_ORG, _APPOINT_ORG, _GAINS_ORG, _IN_TEAM, _FOUNDED), text)
    origin = _first_org(_LEFT_ORG, text)
    if origin and company and normalize(origin) == normalize(company):
        origin = None
    return origin, company


def find_firm(text: str, low: str, exclude: str | None = None) -> str | None:
    """Компания, о которой идёт речь: известная фирма, «в компании X», «партнёр X»."""
    skip = normalize(exclude) if exclude else None
    known = [(m.start(), name) for name, pattern in KNOWN_FIRMS if (m := pattern.search(low)) and normalize(name) != skip]
    if known:
        return min(known)[1]
    for pattern in (_ORG_AFTER_WORD, _ROLE_ORG):
        for m in pattern.finditer(text):
            org = _clean_org(m["org"])
            if org and normalize(org) != skip:
                return org
    return None


def find_role(low: str, start: int = 0, end: int | None = None, last: bool = False) -> str | None:
    """Должность из словаря («старший партнёр», «руководитель практики»): та, что названа раньше всех
    (или позже всех, если last) на участке от `start` до `end`."""
    best: tuple[tuple[int, int], str] | None = None
    for pattern, shown in _ROLES:
        found = list(pattern.finditer(low, start, len(low) if end is None else end))
        if not found:
            continue
        m = found[-1] if last else found[0]
        key = (-m.start() if last else m.start(), m.start() - m.end())
        if best is None or key < best[0]:
            best = (key, shown or m[0].strip())
    return best[1] if best else None


def find_award(text: str) -> str | None:
    """Какая награда или рейтинг: «Chambers Europe», «премия «Юрист года»»; с номинацией, если она названа."""
    found = [m for m in (_AWARD_BRANDS.search(text), _AWARD_NAMED.search(text)) if m]
    if not found:
        return None
    award = " ".join(min(found, key=lambda m: m.start())[0].split())
    nomination = _NOMINATION.search(text)
    return (award + (f", номинация {nomination['nom']}" if nomination else ""))[:100]


def find_law_body(low: str) -> str | None:
    """Кто принял или разъяснил: суд, Госдума, Правительство, ведомство; тот, что назван раньше всех."""
    best: tuple[tuple[int, int], str] | None = None
    for pattern, shown in _LAW_BODIES:
        m = pattern.search(low)
        if m:
            key = (m.start(), m.start() - m.end())
            if best is None or key < best[0]:
                best = (key, shown)
    return best[1] if best else None


def find_doc_refs(text: str) -> str | None:
    """Номера из текста: «63-ФЗ», дела Верховного суда («305-ЭС23-12345») и арбитражные («А40-12345/2024»)."""
    refs: list[str] = []
    for m in _DOC_REF.finditer(text):
        ref = " ".join(m[0].upper().split())
        if ref not in refs:
            refs.append(ref)
    return ", ".join(refs[:2]) or None


def find_in_force(text: str, ref: date) -> date | None:
    """Дата вступления в силу: ближайшая к словам «вступает в силу». Даты после «от» — реквизиты акта, их пропускаем."""
    m = _IN_FORCE.search(normalize(text))
    if not m:
        return None
    start = max(0, m.start() - 70)
    chunk = re.sub(r"\bот\s+\d{1,2}\.\d{2}\.\d{4}", " ", text[start:m.end() + 90])
    hits = [h for h in find_dates(chunk, ref) if not h.deadline]
    return min(hits, key=lambda h: abs(h.start - (m.start() - start))).day if hits else None


# --- Заголовок -----------------------------------------------------------------------------------
_GREETING = re.compile(
    r"^(?:дорогие\s+|уважаемые\s+)?(?:друзья|коллеги|всем\s+привет|привет|здравствуйте|добрый\s+(?:день|вечер)|доброе\s+утро)\W*$",
    re.IGNORECASE,
)


def _clean_lines(text: str) -> list[str]:
    lines = []
    for line in text.splitlines():
        line = re.sub(r"https?://\S+|#\w+|@\w+", " ", line)
        line = re.sub(r"[*_`~|]+", "", line)
        line = re.sub(r"^[^\w«\"(\[]+", "", " ".join(line.split()))
        if line:
            lines.append(line)
    return lines


def make_title(text: str, join_short: bool = False) -> str:
    """Первая осмысленная строка поста. С join_short короткую строку («Налоги и наследство:»)
    дополняем следующей, чтобы заголовок говорил сам за себя."""
    lines = [line for line in _clean_lines(text) if not _GREETING.match(line)]
    if not lines:
        return "(без текста)"
    start = next((i for i, line in enumerate(lines) if len(line) >= 12), 0)
    title = lines[start]
    if join_short and (len(title) < 25 or title.endswith(":")) and start + 1 < len(lines):
        title = f"{title} {lines[start + 1]}"
    return _shorten(title)


def _shorten(line: str, limit: int = 110) -> str:
    if len(line) <= limit:
        return line
    return line[: limit - 1].rsplit(" ", 1)[0] + "…"


def _first_sentences(line: str, limit: int = 200) -> str:
    if len(line) <= limit:
        return line
    cut = line[:limit]
    end = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    return cut[: end + 1] if end >= 60 else cut.rsplit(" ", 1)[0] + "…"


def find_topic(text: str, title: str) -> str | None:
    """«О чём»: первая содержательная строка поста после заголовка, без организационных деталей
    (даты, время, регистрация, ссылки). Грубая выдержка, а не пересказ."""
    for line in _clean_lines(text):
        if _GREETING.match(line) or line in title or title.startswith(line[:40]):
            continue
        if len(line) < 40 or _LOGISTICS.search(normalize(line)):
            continue
        return _first_sentences(line)
    return None


# --- Разбор поста --------------------------------------------------------------------------------
def _event_match(
    text: str, low: str, urls: tuple[str, ...], day: date | None, start: time | None, end: time | None,
    deadline: date | None,
) -> Match:
    title = make_title(text, join_short=True)
    return Match(
        "event", title, day, start, deadline,
        work_format=find_event_format(text), event_end=end, city=find_city(text), price=find_price(text),
        audience=find_audience(low), topic=find_topic(text, title), reg_url=first_link(text, urls),
    )


def _as_event(text: str, low: str, ref: date, urls: tuple[str, ...] = ()) -> Match | None:
    strong = any(w in low for w in EVENT_STRONG)
    weak = any(w in low for w in EVENT_WEAK)
    invites = sum(w in low for w in INVITE_WORDS)
    if _GIVEAWAY.search(low):
        return None
    if not invites and (any(w in low for w in REPORT_WORDS) or _RECORDING.search(low)):
        return None
    if _AD.search(low) and not any(w in low[:160] for w in EVENT_STRONG):
        return None
    hits = find_dates(text, ref)
    dates = [h for h in hits if not h.deadline]
    upcoming = [h for h in dates if h.day >= ref]
    deadline = min((h.day for h in hits if h.deadline and h.day >= ref), default=None)
    if upcoming:
        first = min(upcoming, key=lambda h: h.day)
        when, end = find_time_range(text, first.start)
        if strong or (weak and (when or invites)) or (invites and when):
            return _event_match(text, low, urls, first.day, when, end, deadline)
        return None
    if dates:  # одни прошедшие даты: это отчёт о прошедшем, а не анонс
        return None
    if (strong or weak) and invites >= 2:  # приглашение без даты — покажем отдельно, пусть проверят пост
        return _event_match(text, low, urls, None, None, None, deadline)
    return None


def _sentence_span(low: str, pos: int) -> tuple[int, int]:
    """Границы предложения (или строки), в котором стоит позиция pos."""
    start = max(low.rfind(ch, 0, pos) for ch in ".!?…\n") + 1
    ends = [i for i in (low.find(ch, pos) for ch in ".!?…\n") if i != -1]
    return start, min(ends) if ends else len(low)


def _sentence_at(low: str, pos: int) -> str:
    start, end = _sentence_span(low, pos)
    return low[start:end]


def _is_liability(sentence: str) -> bool:
    return bool(_NOT_CAREER.search(sentence) or (re.search(r"привл[её]ч|привл[её]к", sentence) and "ответственност" in sentence))


_CAREER_CUES = (
    ("Повышение", _NEWS_PROMOTE),
    ("Понижение", _NEWS_DEMOTE),
    ("Карьерный переход", _NEWS_MOVE),
    ("Назначение", _NEWS_APPOINT),
)


def _career(text: str, low: str) -> tuple[str, re.Match] | None:
    """Карьерный ход юриста: переход в другую фирму или компанию, назначение, повышение, понижение.
    Слова «назначен», «избран», «покинул» сами по себе ничего не доказывают, поэтому нужны доказательства:
    названа компания или должность (партнёр, советник, старший юрист…), а в самом предложении нет слов про
    уголовное и административное преследование, штрафы, меры пресечения и назначение дел."""
    origin, company = find_move(text)
    for subtype, pattern in _CAREER_CUES:
        for cue in pattern.finditer(low):
            if _is_liability(_sentence_at(low, cue.start())):
                continue
            role = find_role(low[max(0, cue.start() - 120):cue.end() + 160])
            if (
                subtype in ("Повышение", "Понижение")  # в самих словах названа должность
                or (subtype == "Карьерный переход" and (company or origin or role))
                or (subtype == "Назначение" and role and role != "адвокат")  # «избран в Совет Федерации» не карьера юриста
            ):
                return subtype, cue
    return None


def _as_news(text: str, low: str, channel_title: str, context_required: bool) -> Match | None:
    """Новость о человеке юридического рынка: смена места или должности (переход, назначение, повышение,
    понижение), открытие практики, награда. Достаём, кто (имя), где (компания, откуда ушёл), кем (должность)
    и за что награждён."""
    if len(text) > 1800:  # длинные тексты — статьи и обзоры, а не заметки о людях
        return None
    cue = None
    career = _career(text, low)
    if career:
        subtype, cue = career
    elif _NEWS_LAUNCH.search(low):
        subtype = "Открытие"
    elif _NEWS_AWARD.search(low):
        subtype = "Награда"
    else:
        return None
    people = find_people(text)
    if not people:
        return None
    if context_required and not (_NEWS_CONTEXT.search(low) or _NEWS_CONTEXT.search(normalize(channel_title))):
        return None
    # При переходе новая должность названа после глагола («ранее руководитель в Сбере, перешла … директором»).
    # При повышении и понижении новая должность названа последней: «разжалован из партнёров в советники».
    if cue and subtype in ("Повышение", "Понижение"):
        role = find_role(low, cue.start(), _sentence_span(low, cue.start())[1], last=True)
    else:
        role = (find_role(low, cue.start()) if cue else None) or find_role(low)
    origin = company = place = None
    if subtype != "Награда":
        origin, company = find_move(text)
    company = company or find_firm(text, low, origin)
    if subtype == "Награда":
        place = find_award(text)
    title = make_title(text)
    return Match(
        "news", title, None, None, None, company=company, topic=find_topic(text, title), subtype=subtype,
        people=people, role=role, origin=origin, place=place,
    )


def _as_law(text: str, low: str, ref: date, urls: tuple[str, ...] = ()) -> Match | None:
    """Изменение в законодательстве, судебная практика по трудовым спорам или разъяснение ведомства. Нужны и сам акт
    (закон, суд, ведомство), и слово о перемене (принят, вступает в силу, разъяснил…): так отсекаются просто
    упоминания закона. Решения судов берутся только по трудовым спорам (увольнение, зарплата, отпуск и т. п.)."""
    if len(text) > 3500 or _LAW_AD.search(low) or _GIVEAWAY.search(low):
        return None
    options: list[tuple[int, int, str]] = []  # (где в тексте, порядок при равенстве, тип)
    court = _COURT.search(low) or _ANY_COURT.search(low)
    if court and _COURT_VERB.search(low) and _LABOR.search(low):
        options.append((court.start(), 0, "Судебная практика"))
    bill = _BILL.search(low)
    if bill:
        options.append((bill.start(), 1, "Законопроект"))
    act = _LAW_ACT.search(low)
    if act and _LAW_CHANGE.search(low):
        options.append((act.start(), 2, "Закон"))
    agency = _AGENCY_ACT.search(low)
    if agency:
        options.append((agency.start(), 3, "Разъяснение ведомства"))
    if not options:
        return None
    subtype = min(options)[2]  # что названо в тексте раньше всего, то и главное
    title = make_title(text, join_short=True)
    return Match(
        "law", title, find_in_force(text, ref), None, None, topic=find_topic(text, title), reg_url=first_link(text, urls),
        subtype=subtype, place=find_law_body(low), doc_ref=find_doc_refs(text),
    )


def is_job_channel(title: str) -> bool:
    return bool(_JOB_CHANNEL.search(title))


def _is_editorial(text: str) -> bool:
    lines = _clean_lines(text)
    if not lines:
        return False
    first = normalize(lines[0])
    return first.endswith("?") or first.startswith(_EDITORIAL_START) or "дайджест" in first or bool(_AGGREGATE.search(first))


def _is_vacancy(text: str, low: str, job_channel: bool) -> bool:
    if any(w in low for w in JOB_SEEKER_WORDS) or _CLOSED.search(low) or _JUNK.search(low):
        return False
    if any(t in low for t in VACANCY_TAGS):
        return True
    if _is_editorial(text):
        return False
    structure = any(w in low for w in VACANCY_STRUCTURE)
    details = structure + bool(_PAY.search(low)) + any(w in low for w in VACANCY_APPLY)
    if len(text) > 1500 and details < 2:  # длинные тексты без деталей — статьи и новости
        return False
    role = any(w in low for w in ROLE_WORDS)
    intent = bool(_INTENT.search(low))
    if job_channel:
        # В канале с вакансиями хватает должности в заголовке («Старший юрист в VK») или слов о найме;
        # рекламу и советы без должности в заголовке отсекаем.
        return role and (intent or any(w in normalize(make_title(text)) for w in ROLE_WORDS))
    # Везде остальное (новостные каналы, блоги) — только с явными словами о найме: иначе судебные
    # новости со словами «требования», «директор» и суммой в рублях принимаются за вакансии.
    return intent and role and details >= 1


def is_legal_vacancy(text: str, channel_title: str = "") -> bool:
    """Вакансия из юридической сферы: юридические слова в тексте. Административные роли (офис-менеджер,
    секретарь, ассистент…) подходят только в юридическом контексте: юридические слова в тексте или юридический
    канал. Бухгалтер или маркетолог в канале юридических вакансий без юридических слов в тексте не берутся."""
    low = normalize(text)
    if _LEGAL.search(low):
        return True
    return bool(_LEGAL.search(normalize(channel_title))) and any(w in low for w in ADMIN_ROLES)


def looks_like_agency(text: str) -> bool:
    return bool(_AGENCY.search(normalize(text)))


def extract_contacts(text: str, channel_username: str | None = None, urls: tuple[str, ...] = ()) -> list[str]:
    """Как связаться с работодателем: @ники, e-mail, телефоны и до двух ссылок (например, на hh.ru).
    Ник самого канала не считается контактом."""
    own = (channel_username or "").lower()
    out: list[str] = []

    def add(value: str) -> None:
        if value and value not in out:
            out.append(value)

    for handle in _HANDLE.findall(_EMAIL.sub(" ", text)) + _TME_USER.findall(text):
        if handle.lower() != own:
            add("@" + handle)
    for email in _EMAIL.findall(text):
        add(email)
    for phone in _PHONE.findall(text):
        add(" ".join(phone.split()))
    links = [u.rstrip(".,;:!?") for u in [*urls, *_URL.findall(text)] if "t.me/" not in u]
    for link in dict.fromkeys(links):
        if len([c for c in out if c.startswith("http")]) >= 2:
            break
        add(link)
    return out[:7]


def find_salary(text: str) -> str | None:
    """Сумма из текста («от 250 тыс. руб.») или то, что написано после слова «зарплата»."""
    label = _SALARY_LABEL.search(text)
    fragment = label[1] if label else None
    money = _MONEY.search(fragment) if fragment else _MONEY.search(text)
    if money:
        return " ".join(money[0].split()).rstrip(" ,;")
    return " ".join(fragment.split()).rstrip(".;, ") if fragment else None


def find_format(text: str) -> str | None:
    low = normalize(text)
    found = []
    if re.search(r"удаленн|remote|дистанцион", low):
        found.append("удалённо")
    if "гибрид" in low:
        found.append("гибрид")
    if re.search(r"офис(?![-\s]?менедж)|\boffice\b(?! manager)", low):
        found.append("офис")
    return " / ".join(found) or None


def find_company(title: str, text: str) -> str | None:
    """Название работодателя: по подписи «Работодатель:», в кавычках в заголовке, перед словом «ищет»
    или после «в» в заголовке. Если не нашли, лучше пусто, чем неверно."""
    label = _COMPANY_LABEL.search(text)
    candidates = [
        label[1] if label else None,
        (_QUOTED.search(title) or [None, None])[1],
        (_COMPANY_ASKS.search(title) or [None, None])[1],
        (_COMPANY_IN.search(title) or [None, None])[1],
    ]
    for candidate in candidates:
        if candidate:
            cleaned = candidate.strip().strip("«»\"“” ").rstrip(" .,:;")
            if cleaned and not _GENERIC_COMPANY.search(cleaned):
                return cleaned[:60]
    return None


def classify(
    text: str,
    posted: date,
    channel_title: str = "",
    channel_username: str | None = None,
    urls: tuple[str, ...] = (),
    kinds: tuple[str, ...] = ("event", "vacancy", "news", "law"),
    news_context_required: bool = True,
    channel_id: int | None = None,
) -> Match | None:
    """То же, что `_classify`, и дополнительно к найденному прикладывает ссылки из самого поста."""
    match = _classify(text, posted, channel_title, channel_username, urls, kinds, news_context_required)
    if match is None:
        return None
    return replace(match, links=find_links(text, urls, channel_username, channel_id))


def _classify(
    text: str,
    posted: date,
    channel_title: str,
    channel_username: str | None,
    urls: tuple[str, ...],
    kinds: tuple[str, ...],
    news_context_required: bool,
) -> Match | None:
    """Мероприятие, вакансия, новость о людях или изменение в законодательстве и практике (в таком приоритете)
    либо None. `posted` — дата публикации поста, `kinds` ограничивает, что искать (для каналов, настроенных
    «только мероприятия» и т. п.). В каналах, которые вы сами пометили «news», юридический контекст новости
    не проверяем."""
    low = normalize(text)
    if "event" in kinds:
        event = _as_event(text, low, posted, urls)
        if event:
            return event
    if "vacancy" in kinds and _is_vacancy(text, low, is_job_channel(channel_title)):
        title = make_title(text)
        return Match(
            "vacancy", title, None, None, None,
            company=find_company(title, text),
            salary=find_salary(text),
            work_format=find_format(text),
            contacts=tuple(extract_contacts(text, channel_username, urls)),
            via_agency=looks_like_agency(text),
            city=find_city(text),
        )
    news = _as_news(text, low, channel_title, news_context_required) if "news" in kinds else None
    if news:  # переход, назначение, награда — главное для охоты за людьми, раньше раздела о законах
        return news
    return _as_law(text, low, posted, urls) if "law" in kinds else None


def passes_filters(text: str, only: tuple[str, ...], exclude: tuple[str, ...]) -> bool:
    low = normalize(text)
    if exclude and any(w in low for w in exclude):
        return False
    return not only or any(w in low for w in only)


