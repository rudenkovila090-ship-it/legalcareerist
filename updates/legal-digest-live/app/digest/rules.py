def _surname_nominative(last: str, first_nominative: str) -> str:
    female = (first_nominative.endswith(("а", "я")) and first_nominative not in _MALE_A) or first_nominative == "любовь"
    for oblique, nominative in (_FEMALE_SURNAME_FORMS if female else _MALE_SURNAME_FORMS):
        if last.lower().endswith(oblique):
            return last[: len(last) - len(oblique)] + nominative
    return last


def _person(first: str, last: str) -> tuple[str, str] | None:
    """Имя и фамилия в именительном падеже, если first — известное имя (в любом падеже), а last похоже на фамилию."""
    nf, nl = normalize(first), normalize(last)
    nominative = _FIRST_FORMS.get(nf)
    if nominative is None or nl in _FIRST_FORMS or not _SURNAME.search(nl):
        return None
    if nf == nominative:
        return first, last
    return nominative.capitalize(), _surname_nominative(last, nominative)
